    await page.route('**/storage/maintenance',route=>route.abort('failed'));
    await page.getByRole('button',{name:'执行本批策略',exact:true}).click();await page.getByRole('button',{name:'确认执行本批',exact:true}).click();
    await page.getByRole('heading',{name:'提交结果未知',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'预览下一批',exact:true}).count(),0);
    await page.unroute('**/storage/maintenance');checks.push('unknown result remains explicit; no automatic replay or next batch');
    await page.setViewportSize({width:760,height:1000}); await screenshot('storage-narrow.png');
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.setViewportSize({width:1512,height:1100});
