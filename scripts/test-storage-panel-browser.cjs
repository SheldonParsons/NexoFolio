    await page.getByText('策略预览 · 未提交',{exact:true}).waitFor();
    await page.getByRole('button',{name:'执行本批策略',exact:true}).click();
    await page.getByRole('alertdialog').waitFor();
    await screenshot('storage-confirm.png');
    await page.getByRole('button',{name:'取消',exact:true}).click();
    assert(!network.some(x=>x.method==='POST'&&x.path.endsWith('maintenance')&&x.status!==200));
    await page.getByRole('button',{name:'执行本批策略',exact:true}).click();
    const response = page.waitForResponse(r=>r.url().endsWith('/maintenance') && r.request().postDataJSON()?.action==='execute');
    await page.getByRole('button',{name:'确认执行本批',exact:true}).click();
    const execution=await (await response).json(); assert.equal(execution.report.compacted,3); assert.equal(execution.report.committed,true);
    await page.getByText('本批已提交',{exact:true}).waitFor();
    await page.locator('.storage-result').scrollIntoViewIfNeeded(); await screenshot('storage-result.png');
    checks.push('preview rolls back; confirmation cancel; actual execute compacted three; protected items skipped');
    // A failed GET retains the old sample; a stale sample is explicitly labelled.
    const endpoint='**/v1/projects/'+m.project+'/storage';
    await page.route(endpoint,route=>route.fulfill({status:503,contentType:'application/json',body:'{"error":{"message":"合成统计读取失败"}}'}));
    await page.getByRole('button',{name:'刷新统计',exact:true}).click();
